// プレイヤーが使用できるキャラクターリスト
const PLAYER_CHARACTERS = ['ronin'];

// 敵として出現するキャラクターリスト
const ENEMY_CHARACTERS = ['wakaSamurai', 'oldMaster', 'onnaSamurai', 'souhei', 'shinobi', 'nobushi'];

// ランダムな敵を取得
function getRandomEnemy() {
    const index = Math.floor(Math.random() * ENEMY_CHARACTERS.length);
    return CHARACTERS[ENEMY_CHARACTERS[index]];
}

// キャラクターIDからキャラクターを取得
function getCharacter(id) {
    return CHARACTERS[id];
}
